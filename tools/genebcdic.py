#!/usr/bin/env python3
"""Generate src/ebcdic_tab.c: ISO-8859-1 <-> IBM-1047 tables (dev time only).

Uses iconv(1), converting one byte at a time so unmapped bytes can be
replaced by the substitution characters."""
import subprocess
import sys


def conv(frm, to, b):
    r = subprocess.run(["iconv", "-f", frm, "-t", to], input=bytes([b]),
                       capture_output=True)
    if r.returncode != 0 or len(r.stdout) != 1:
        return None
    return r.stdout[0]


def main():
    a2e = [conv("ISO-8859-1", "IBM1047", i) for i in range(256)]
    e2a = [conv("IBM1047", "ISO-8859-1", i) for i in range(256)]
    a2e = [0x3F if v is None else v for v in a2e]
    e2a = [0x1A if v is None else v for v in e2a]
    out = ["/* Generated by tools/genebcdic.py; DO NOT EDIT. */", "",
           '#include "ebcdic.h"', ""]
    for name, t in (("za_to_ebcdic", a2e), ("za_to_latin1", e2a)):
        out.append("const unsigned char %s[256] = {" % name)
        for i in range(0, 256, 16):
            out.append("    " + ", ".join("0x%02X" % v for v in t[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    sys.stdout.write("\n".join(out))


main()
